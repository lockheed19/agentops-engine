import json
from langchain_core.messages import AIMessage, SystemMessage, ToolMessage
from langchain_groq import ChatGroq
from src.agent.tools import incident_tools
from src.config import settings
from src.core.state import AgentState
#human in the loop imports
from langchain_core.messages import HumanMessage

# Initialize Groq LLM with tools bound
llm = ChatGroq(
    api_key=settings.GROQ_API_KEY,
    model=settings.MODEL_NAME,
    temperature=0.1,
)
llm_with_tools = llm.bind_tools(incident_tools)

SYSTEM_PROMPT = """You are an Autonomous Site Reliability Engineering (SRE) Incident Triage Specialist.
Your task is to investigate production incidents systematically:
1. Gather infrastructure metrics and recent logs for degraded services.
2. If database pressure or lock waits are suspected, inspect DB connection pools and queries.
3. Formulate a root cause hypothesis based on gathered diagnostic evidence.
4. If remediation is required, propose an action using the `execute_remediation_action` tool.

Be concise, precise, and systematic in your tool calls and reasoning."""

async def triage_investigator_node(state: AgentState) -> dict:
    """Primary decision node: analyzes current state/messages and invokes diagnostic tools or proposes root cause."""
    messages = state["messages"]
    if not any(isinstance(m, SystemMessage) for m in messages):
        messages = [SystemMessage(content=SYSTEM_PROMPT)] + messages

    response = await llm_with_tools.ainvoke(messages)
    return {"messages": [response]}

async def tool_execution_node(state: AgentState) -> dict:
    """Executes tool calls generated by the LLM and appends ToolMessages to the graph state."""
    last_message = state["messages"][-1]
    tool_messages = []

    tool_map = {tool.name: tool for tool in incident_tools}

    if hasattr(last_message, "tool_calls") and last_message.tool_calls:
        for tool_call in last_message.tool_calls:
            tool_name = tool_call["name"]
            tool_args = tool_call["args"]
            tool_call_id = tool_call["id"]

            if tool_name in tool_map:
                tool_instance = tool_map[tool_name]
                # Invoke the async tool directly
                output = await tool_instance.ainvoke(tool_args)
                tool_messages.append(
                    ToolMessage(
                        content=json.dumps(output) if not isinstance(output, str) else output,
                        tool_call_id=tool_call_id,
                        name=tool_name,
                    )
                )

    return {"messages": tool_messages}

async def root_cause_synthesizer_node(state: AgentState) -> dict:
    """Node responsible for finalizing the Incident State summary based on tool findings."""
    messages = state["messages"]
    synthesis_prompt = SystemMessage(
        content="Summarize the incident findings: identify the primary root cause, severity, and impacted service explicitly."
    )
    summary_response = await llm.ainvoke(messages + [synthesis_prompt])

    return {
        "root_cause_hypothesis": summary_response.content,
        "messages": [summary_response],
    }

async def human_approval_gate_node(state: AgentState) -> dict:
    """Interruption boundary: validates whether human operator authorized remediation execution."""
    remediation_approved = state.get("remediation_approved", False)

    if not remediation_approved:
        return {
            "messages": [
                HumanMessage(
                    content="[SYSTEM INTERRUPT]: Automated remediation blocked. Waiting for operator authorization."
                )
            ]
        }

    return {
        "messages": [
            HumanMessage(
                content="[OPERATOR APPROVED]: Human authorization granted for remediation execution."
            )
        ]
    }